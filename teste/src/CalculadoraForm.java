    private void calcular() {
        try {
            double a = Double.parseDouble(campoA.getText().replace(',', '.'));
            double b = 0;
            int op = operacoes.getSelectedIndex();
            if (op != 5) {
                b = Double.parseDouble(campoB.getText().replace(',', '.'));
            }

            double r;
            switch (op) {
                case 0:
                    r = a + b;
                    break;
                case 1:
                    r = a - b;
                    break;
                case 2:
                    r = a * b;
                    break;
                case 3:
                    if (b == 0) {
                        resultado.setText("Divisão por zero");
                        return;
                    }
                    r = a / b;
                    break;
                case 4:
                    r = Math.pow(a, b);
                    break;
                default:
                    if (a < 0) {
                        resultado.setText("Raiz de negativo");
                        return;
                    }
                    r = Math.sqrt(a);
            }
            resultado.setText(String.valueOf(r));
        } catch (NumberFormatException ex) {
            resultado.setText("Número inválido");
        }
    }

